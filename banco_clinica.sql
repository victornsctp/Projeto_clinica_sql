DROP TABLE IF EXISTS consulta_exames;
DROP TABLE IF EXISTS consultas;
DROP TABLE IF EXISTS exames;
DROP TABLE IF EXISTS pacientes;
DROP TABLE IF EXISTS convenios;
DROP TABLE IF EXISTS medicos;
DROP TABLE IF EXISTS especialidades;

CREATE TABLE especialidades (
    id   INTEGER PRIMARY KEY,
    nome VARCHAR(50) NOT NULL
);

CREATE TABLE medicos (
    id               INTEGER PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    especialidade_id INTEGER NOT NULL,
    data_admissao    DATE NOT NULL,
    coordenador_id   INTEGER,           -- aponta para outro médico (NULL = sem coordenador)
    FOREIGN KEY (especialidade_id) REFERENCES especialidades(id),
    FOREIGN KEY (coordenador_id)   REFERENCES medicos(id)
);

CREATE TABLE convenios (
    id                  INTEGER PRIMARY KEY,
    nome                VARCHAR(60) NOT NULL,
    percentual_repasse  INTEGER NOT NULL  -- % do valor particular que o convênio paga à clínica
);

CREATE TABLE pacientes (
    id              INTEGER PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL,
    sexo            CHAR(1) NOT NULL,
    data_nascimento DATE NOT NULL,
    cidade          VARCHAR(60),
    convenio_id     INTEGER,            -- NULL = paciente particular
    data_cadastro   DATE NOT NULL,
    FOREIGN KEY (convenio_id) REFERENCES convenios(id)
);

CREATE TABLE consultas (
    id              INTEGER PRIMARY KEY,
    paciente_id     INTEGER NOT NULL,
    medico_id       INTEGER NOT NULL,
    data_consulta   DATE NOT NULL,
    tipo            VARCHAR(20) NOT NULL,   -- 'Primeira consulta' ou 'Retorno'
    status          VARCHAR(20) NOT NULL,   -- Realizada, Cancelada, Faltou, Agendada
    valor           DECIMAL(10,2) NOT NULL, -- valor da consulta (só vira receita se Realizada)
    forma_pagamento VARCHAR(30),
    FOREIGN KEY (paciente_id) REFERENCES pacientes(id),
    FOREIGN KEY (medico_id)   REFERENCES medicos(id)
);

CREATE TABLE exames (
    id    INTEGER PRIMARY KEY,
    nome  VARCHAR(80) NOT NULL,
    valor DECIMAL(10,2) NOT NULL
);

CREATE TABLE consulta_exames (
    id             INTEGER PRIMARY KEY,
    consulta_id    INTEGER NOT NULL,
    exame_id       INTEGER NOT NULL,
    data_resultado DATE,                -- NULL = resultado ainda pendente
    FOREIGN KEY (consulta_id) REFERENCES consultas(id),
    FOREIGN KEY (exame_id)    REFERENCES exames(id)
);

